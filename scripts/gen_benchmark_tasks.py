#!/usr/bin/env python3
"""Deterministically generate hard-benchmark-v2 candidate tasks whose `gold`
is computed or exhaustively verified, so a human mainly reviews difficulty
and approves instead of authoring and hand-checking every answer
(docs/operations/benchmark-v2.md, WP-2b authoring recipe).

All six families use synthetic, license-clean templates: computed arithmetic
(`math`/`japanese`), executable-semantics simulation (`coding`), exhaustive
solution/order enumeration (`logic`/`planning`), and cross-referenced
generated records (`long_context`).

Every emitted row is `review_status: "pending"`. Output is NOT the approved
benchmark: a human must still confirm difficulty calibration (the 40-70%
accuracy band, ceiling/floor swaps) and set `review_status: "approved"`.
"""

from __future__ import annotations

import argparse
import io
import json
import random
from contextlib import redirect_stdout
from itertools import permutations, product
from typing import Callable, Dict, List, Optional, Tuple

FAMILIES = ("math", "coding", "logic", "planning", "long_context", "japanese")
DIFFICULTIES = ("easy", "medium", "hard")

# Number of chained operations / puzzle size per difficulty tier. Larger
# tiers exist to push past the Phase 1 ceiling effect; the human still
# confirms the empirical accuracy band during calibration.
_MATH_STEPS = {"easy": 2, "medium": 4, "hard": 6}
_MATH_MAGNITUDE = {"easy": 20, "medium": 200, "hard": 2000}
_LOGIC_PEOPLE = {"easy": 3, "medium": 4, "hard": 5}


def _norm_grader(value: str) -> dict:
    return {"type": "exact", "value": value, "normalize": True}


def _unit_label(value: int) -> str:
    return "unit" if value == 1 else "units"


def generate_math_task(rng: random.Random, difficulty: str, task_id: str) -> dict:
    """A multi-step arithmetic word problem with an integer answer computed
    here, so `gold` is correct by construction."""
    steps = _MATH_STEPS[difficulty]
    hi = _MATH_MAGNITUDE[difficulty]
    start = rng.randint(hi // 2, hi)
    value = start
    lines = [f"A depot starts with {start} units."]
    rationale = [f"start = {start}"]
    for _ in range(steps):
        op = rng.choice(("add", "sub", "mul_add"))
        if op == "add":
            a = rng.randint(1, hi)
            value += a
            lines.append(f"It receives {a} more {_unit_label(a)}.")
            rationale.append(f"+ {a} = {value}")
        elif op == "sub":
            a = rng.randint(1, max(1, value // 2))
            value -= a
            lines.append(f"It ships out {a} {_unit_label(a)}.")
            rationale.append(f"- {a} = {value}")
        else:
            batches = rng.randint(2, 5)
            per = rng.randint(1, hi // 10 + 1)
            value += batches * per
            lines.append(f"It receives {batches} pallets of {per} {_unit_label(per)} each.")
            rationale.append(f"+ {batches}x{per} = {value}")
    prompt = (
        " ".join(lines)
        + " How many units are in the depot at the end?"
        + " Answer with the integer only."
    )
    gold = str(value)
    return {
        "id": task_id,
        "family": "math",
        "difficulty": difficulty,
        "answer_type": "single",
        "prompt": prompt,
        "gold": gold,
        "grader": _norm_grader(gold),
        "review_status": "pending",
        "gold_rationale": "; ".join(rationale),
        "source": "generated by scripts/gen_benchmark_tasks.py (parameterized template)",
    }


Statement = Tuple[int, str, int, int]


def _statement_truth(statement: Statement, assignment: Tuple[bool, ...]) -> bool:
    _, kind, a, b = statement
    if kind == "knight":
        return assignment[a]
    if kind == "knave":
        return not assignment[a]
    if kind == "same":
        return assignment[a] == assignment[b]
    if kind == "different":
        return assignment[a] != assignment[b]
    if kind == "count_eq":
        return sum(assignment) == a
    if kind == "count_ge":
        return sum(assignment) >= a
    raise ValueError(f"unknown statement kind: {kind}")


def _solve_knights_knaves(statements: List[Statement], n: int) -> List[Tuple[bool, ...]]:
    """Return every truth assignment (True=knight) consistent with all
    statements. A speaker's type must equal the truth value of their claim."""
    solutions = []
    for assignment in product((True, False), repeat=n):
        ok = True
        for statement in statements:
            speaker = statement[0]
            claim = _statement_truth(statement, assignment)
            # A knight (True) speaks truth; a knave (False) lies.
            if assignment[speaker] != claim:
                ok = False
                break
        if ok:
            solutions.append(assignment)
    return solutions


def generate_logic_task(rng: random.Random, difficulty: str, task_id: str) -> dict:
    """A knights-and-knaves puzzle whose unique solution is confirmed by
    exhaustive enumeration before it is emitted; `gold` is the number of
    knights."""
    n = _LOGIC_PEOPLE[difficulty]
    names = ["Alice", "Bob", "Carol", "Dave", "Erin"][:n]
    all_predicates = []
    for target in range(n):
        all_predicates.extend((("knight", target, -1), ("knave", target, -1)))
    for a in range(n):
        for b in range(a + 1, n):
            all_predicates.extend((("same", a, b), ("different", a, b)))
    for count in range(n + 1):
        all_predicates.append(("count_eq", count, -1))
    for count in range(1, n + 1):
        all_predicates.append(("count_ge", count, -1))

    for _ in range(5000):
        hidden = tuple(rng.choice((True, False)) for _ in range(n))
        if all(hidden) or not any(hidden):
            continue
        statements: List[Statement] = []
        for speaker in range(n):
            compatible = [
                (speaker, kind, a, b)
                for kind, a, b in all_predicates
                if _statement_truth((speaker, kind, a, b), hidden) == hidden[speaker]
            ]
            statements.append(rng.choice(compatible))
        solutions = _solve_knights_knaves(statements, n)
        if len(solutions) == 1:
            break
    else:  # pragma: no cover - astronomically unlikely with n<=5
        raise RuntimeError("could not find a unique-solution puzzle")
    solution = solutions[0]
    sentences = []
    for speaker, kind, a, b in statements:
        if kind == "knight":
            claim_text = f"{names[a]} is a knight"
        elif kind == "knave":
            claim_text = f"{names[a]} is a knave"
        elif kind == "same":
            claim_text = f"{names[a]} and {names[b]} are the same type"
        elif kind == "different":
            claim_text = f"{names[a]} and {names[b]} are different types"
        elif kind == "count_eq":
            claim_text = f"exactly {a} of us are knights"
        else:
            claim_text = f"at least {a} of us are knights"
        sentences.append(f'{names[speaker]} says, "{claim_text}."')
    knights = sum(1 for is_knight in solution if is_knight)
    prompt = (
        "On an island every person is either a knight (always tells the truth) "
        "or a knave (always lies). "
        + " ".join(sentences)
        + " How many of them are knights? Answer with the integer only."
    )
    gold = str(knights)
    rationale = ", ".join(
        f"{names[i]}={'knight' if is_knight else 'knave'}" for i, is_knight in enumerate(solution)
    )
    return {
        "id": task_id,
        "family": "logic",
        "difficulty": difficulty,
        "answer_type": "single",
        "prompt": prompt,
        "gold": gold,
        "grader": _norm_grader(gold),
        "review_status": "pending",
        "gold_rationale": f"unique solution: {rationale}; knights={knights}",
        "source": "generated by scripts/gen_benchmark_tasks.py (exhaustive knights-and-knaves)",
    }


def generate_coding_task(rng: random.Random, difficulty: str, task_id: str) -> dict:
    """Generate a short deterministic Python trace question and run it."""
    iterations = {"easy": 3, "medium": 6, "hard": 10}[difficulty]
    start = rng.randint(1, 20)
    multiplier = rng.randint(2, 4)
    modulus = rng.choice((17, 29, 47, 97))
    program = (
        f"value = {start}\n"
        f"for i in range({iterations}):\n"
        f"    value = (value * {multiplier} + i) % {modulus}\n"
        "print(value)\n"
    )
    output = io.StringIO()
    with redirect_stdout(output):
        exec(program, {"__builtins__": {"print": print, "range": range}}, {})
    gold = output.getvalue().strip()
    if not gold.isdecimal():  # pragma: no cover - the emitted program is fixed above
        raise RuntimeError(f"coding task produced unexpected output: {gold!r}")
    prompt = (
        "What integer does this Python program print?\n\n"
        + program
        + "\nAnswer with the integer only."
    )
    return {
        "id": task_id,
        "family": "coding",
        "difficulty": difficulty,
        "answer_type": "single",
        "prompt": prompt,
        "gold": gold,
        "grader": _norm_grader(gold),
        "review_status": "pending",
        "gold_rationale": "executed program output: " + gold,
        "source": "generated by scripts/gen_benchmark_tasks.py (executed Python program)",
    }


def _count_topological_orders(n: int, edges: List[Tuple[int, int]]) -> int:
    count = 0
    for order in permutations(range(n)):
        position = {node: index for index, node in enumerate(order)}
        if all(position[before] < position[after] for before, after in edges):
            count += 1
    return count


def generate_planning_task(rng: random.Random, difficulty: str, task_id: str) -> dict:
    """Generate an acyclic dependency plan and exhaustively count every
    valid ordering."""
    n = {"easy": 4, "medium": 5, "hard": 6}[difficulty]
    labels = [chr(ord("A") + i) for i in range(n)]
    while True:
        edges = []
        for before in range(n):
            for after in range(before + 1, n):
                probability = {"easy": 0.25, "medium": 0.35, "hard": 0.45}[difficulty]
                if rng.random() < probability:
                    edges.append((before, after))
        count = _count_topological_orders(n, edges)
        if edges and 1 <= count < _factorial(n):
            break
    dependencies = ", ".join(f"{labels[a]} before {labels[b]}" for a, b in edges)
    prompt = (
        f"Tasks {', '.join(labels)} must each be performed exactly once. "
        f"The dependencies are: {dependencies}. "
        "How many valid complete task orders satisfy all dependencies? "
        "Answer with the integer only."
    )
    gold = str(count)
    return {
        "id": task_id,
        "family": "planning",
        "difficulty": difficulty,
        "answer_type": "single",
        "prompt": prompt,
        "gold": gold,
        "grader": _norm_grader(gold),
        "review_status": "pending",
        "gold_rationale": f"exhaustive enumeration of {n}! permutations found {count} valid orders",
        "source": "generated by scripts/gen_benchmark_tasks.py (exhaustive DAG ordering)",
    }


def _factorial(n: int) -> int:
    result = 1
    for value in range(2, n + 1):
        result *= value
    return result


def generate_long_context_task(rng: random.Random, difficulty: str, task_id: str) -> dict:
    """Generate a >2,000-character record set and a cross-reference question
    whose answer is recomputed from two distant records."""
    records = []
    count = {"easy": 24, "medium": 30, "hard": 36}[difficulty]
    for index in range(count):
        code = f"R{index + 1:02d}"
        units = rng.randint(100, 999)
        region = rng.choice(("north", "south", "east", "west"))
        note = (
            f"Record {code} belongs to the {region} division. Its audited unit total is "
            f"{units}. The record was independently checked and contains no adjustment. "
            f"Use the audited unit total, not the record number, in calculations."
        )
        records.append((code, units, note))
    left_index = rng.randrange(0, count // 3)
    right_index = rng.randrange(2 * count // 3, count)
    left, right = records[left_index], records[right_index]
    passage = "\n\n".join(record[2] for record in records)
    gold_value = left[1] + right[1]
    prompt = (
        f"{passage}\n\nQuestion: Add the audited unit totals for records "
        f"{left[0]} and {right[0]}. Answer with the integer only."
    )
    gold = str(gold_value)
    return {
        "id": task_id,
        "family": "long_context",
        "difficulty": difficulty,
        "answer_type": "single",
        "prompt": prompt,
        "gold": gold,
        "grader": _norm_grader(gold),
        "review_status": "pending",
        "gold_rationale": f"{left[0]}={left[1]}; {right[0]}={right[1]}; sum={gold_value}",
        "source": "generated by scripts/gen_benchmark_tasks.py (synthetic records)",
    }


def generate_japanese_task(rng: random.Random, difficulty: str, task_id: str) -> dict:
    """Generate a native-Japanese multi-step inventory problem."""
    steps = _MATH_STEPS[difficulty]
    hi = _MATH_MAGNITUDE[difficulty]
    value = rng.randint(hi // 2, hi)
    lines = [f"倉庫には最初に{value}個の商品があります。"]
    rationale = [f"開始={value}"]
    for _ in range(steps):
        if rng.choice((True, False)):
            amount = rng.randint(1, max(2, _MATH_MAGNITUDE[difficulty] // 3))
            value += amount
            lines.append(f"{amount}個入荷しました。")
            rationale.append(f"+{amount}={value}")
        else:
            amount = rng.randint(1, max(1, value // 3))
            value -= amount
            lines.append(f"{amount}個出荷しました。")
            rationale.append(f"-{amount}={value}")
    prompt = "".join(lines) + "最後に商品は何個ありますか。整数だけで答えてください。"
    gold = str(value)
    return {
        "id": task_id,
        "family": "japanese",
        "difficulty": difficulty,
        "answer_type": "single",
        "prompt": prompt,
        "gold": gold,
        "grader": _norm_grader(gold),
        "review_status": "pending",
        "gold_rationale": "; ".join(rationale),
        "source": "generated by scripts/gen_benchmark_tasks.py (日本語パラメータ化テンプレート)",
    }


_GENERATORS: Dict[str, Callable[[random.Random, str, str], dict]] = {
    "math": generate_math_task,
    "coding": generate_coding_task,
    "logic": generate_logic_task,
    "planning": generate_planning_task,
    "long_context": generate_long_context_task,
    "japanese": generate_japanese_task,
}


def _unique_task(
    generator: Callable[[random.Random, str, str], dict],
    rng: random.Random,
    difficulty: str,
    task_id: str,
    seen_prompts: set,
) -> dict:
    for _ in range(1000):
        task = generator(rng, difficulty, task_id)
        if task["prompt"] not in seen_prompts:
            seen_prompts.add(task["prompt"])
            return task
    raise RuntimeError(f"could not generate a unique prompt for {task_id}")


def generate_tasks(
    *,
    per_family_per_difficulty: int,
    seed: int,
    id_prefix: str = "genv2",
    families: Optional[Tuple[str, ...]] = None,
) -> List[dict]:
    """Deterministic: the same (seed, counts) always produce the same tasks."""
    families = families or FAMILIES
    rng = random.Random(seed)
    tasks: List[dict] = []
    seen_prompts = set()
    for family in families:
        generator = _GENERATORS[family]
        for difficulty in DIFFICULTIES:
            for index in range(per_family_per_difficulty):
                task_id = f"{id_prefix}-{family}-{difficulty}-{index + 1}"
                tasks.append(_unique_task(generator, rng, difficulty, task_id, seen_prompts))
    return tasks


_SPLIT_DIFFICULTY_COUNTS = {
    "calibration": {"easy": 1, "medium": 2, "hard": 2},
    "dev": {"easy": 2, "medium": 4, "hard": 4},
    "test": {"easy": 2, "medium": 4, "hard": 4},
}


def generate_draft_splits(*, seed: int, id_prefix: str = "genv2") -> Dict[str, List[dict]]:
    """Generate structurally valid pending-review 30/60/60 draft splits.

    Per family: calibration=5, dev=10, test=10. Each split is exactly 20%
    easy, and test contains exactly 10 tasks per family. Prompts are unique
    across all three files. The test split is a draft, not locked/approved.
    """
    rng = random.Random(seed)
    seen_prompts = set()
    splits: Dict[str, List[dict]] = {}
    for split, difficulty_counts in _SPLIT_DIFFICULTY_COUNTS.items():
        rows = []
        for family in FAMILIES:
            generator = _GENERATORS[family]
            for difficulty, count in difficulty_counts.items():
                for index in range(count):
                    task_id = f"{id_prefix}-{split}-{family}-{difficulty}-{index + 1}"
                    rows.append(_unique_task(generator, rng, difficulty, task_id, seen_prompts))
        splits[split] = rows
    return splits


def _write_jsonl(path: str, tasks: List[dict]) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        for task in tasks:
            fh.write(json.dumps(task, ensure_ascii=False) + "\n")


def main(argv: Optional[list] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    output = parser.add_mutually_exclusive_group(required=True)
    output.add_argument("--output", help="write one candidate-pool JSONL")
    output.add_argument(
        "--output-dir",
        help="write structurally valid pending-review calibration/dev/test drafts",
    )
    parser.add_argument(
        "--per-family-per-difficulty",
        type=int,
        default=4,
        help="tasks per (family, difficulty) cell",
    )
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--id-prefix", default="genv2")
    args = parser.parse_args(argv)

    if args.per_family_per_difficulty < 1:
        parser.error("--per-family-per-difficulty must be positive")

    if args.output:
        tasks = generate_tasks(
            per_family_per_difficulty=args.per_family_per_difficulty,
            seed=args.seed,
            id_prefix=args.id_prefix,
        )
        _write_jsonl(args.output, tasks)
        print(f"wrote {args.output} ({len(tasks)} tasks, review_status=pending)")
        return 0

    from pathlib import Path

    output_dir = Path(args.output_dir)
    paths = {split: output_dir / f"tasks-v2-{split}.jsonl" for split in _SPLIT_DIFFICULTY_COUNTS}
    existing = [str(path) for path in paths.values() if path.exists()]
    if existing:
        parser.error("refusing to overwrite existing benchmark file(s): " + ", ".join(existing))
    splits = generate_draft_splits(seed=args.seed, id_prefix=args.id_prefix)
    output_dir.mkdir(parents=True, exist_ok=True)
    for split, tasks in splits.items():
        _write_jsonl(str(paths[split]), tasks)
        print(f"wrote {paths[split]} ({len(tasks)} tasks, review_status=pending)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
